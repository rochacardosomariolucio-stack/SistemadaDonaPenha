    public void carregarVendasTabela() {
        // Pega o modelo da sua jTable1
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        modelo.setNumRows(0); // Limpa a tabela antes de carregar

        dao.ProdutoDAO daoVendas = new dao.ProdutoDAO();
        double faturamentoTotal = 0;

        // Preenche as linhas
        for (Object[] venda : daoVendas.listarVendas()) {
            modelo.addRow(venda);
            faturamentoTotal += (double) venda[4]; // Soma o Valor Total (posição 4 do array)
        }

        // Atualiza o texto do TOTAL VENDIDO (seu jLabel1)
        jLabel1.setText("TOTAL VENDIDO: R$ " + String.format("%.2f", faturamentoTotal));
    }

