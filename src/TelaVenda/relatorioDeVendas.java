    private void btnLimparHistoricoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimparHistoricoActionPerformed

        int resposta = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente apagar TODO o histórico de vendas?\nEsta ação não pode ser desfeita!",
                "AVISO DE SEGURANÇA",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        // 2. Se ele clicar em SIM
        if (resposta == javax.swing.JOptionPane.YES_OPTION) {
            dao.ProdutoDAO daoVendas = new dao.ProdutoDAO();

            if (daoVendas.limparHistoricoVendas()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Histórico limpo com sucesso!");
                carregarVendasTabela(); // Recarrega a tabela (que agora virá vazia)
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao limpar o histórico no banco de dados.");
            }
        }
    
    }//GEN-LAST:event_btnLimparHistoricoActionPerformed

