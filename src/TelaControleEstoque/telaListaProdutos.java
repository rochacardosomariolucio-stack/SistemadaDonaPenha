    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int linhaSelecionada = jTable1.getSelectedRow();

        if (linhaSelecionada != -1) {
            // Pega os dados REAIS da linha que você clicou
            int id = (int) jTable1.getValueAt(linhaSelecionada, 0);
            String nome = (String) jTable1.getValueAt(linhaSelecionada, 1);

            // Abre a tela passando o ID e o Nome REAIS
            gerenciarEstoque gestoque = new gerenciarEstoque(id, nome);
            gestoque.setVisible(true);

            // Opcional: Atualiza a lista quando fechar a edição
            gestoque.addWindowListener(new java.awt.event.WindowAdapter() {
                @Override
                public void windowClosed(java.awt.event.WindowEvent e) {
                    carregarTabela(); // Recarrega para mostrar o preço/nome novo
                }
            });
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um produto real na tabela!");
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String busca = jTextField1.getText().trim();
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();

        // Filtro simples via Java (para não complicar o SQL agora)
        final javax.swing.table.TableRowSorter<javax.swing.table.TableModel> sorter = new javax.swing.table.TableRowSorter<>(modelo);
        jTable1.setRowSorter(sorter);

        if (busca.length() == 0) {
            sorter.setRowFilter(null);
        } else {
            // Filtra pelo nome do produto (coluna index 1)
            sorter.setRowFilter(javax.swing.RowFilter.regexFilter("(?i)" + busca, 1));
        }
    }//GEN-LAST:event_jButton2ActionPerformed

