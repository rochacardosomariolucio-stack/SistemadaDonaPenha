    public class AlertaRenderer extends DefaultTableCellRenderer {

        @Override
        public Component getTableCellRendererComponent(JTable table, Object value, boolean isSelected, boolean hasFocus, int row, int column) {
            Component c = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);

            Object valorAlerta = table.getValueAt(row, 4);
            String status = (valorAlerta != null) ? valorAlerta.toString() : "";

            if (!isSelected) {
                // Mantemos o texto em preto para melhor legibilidade nas cores claras
                c.setForeground(Color.BLACK);

                switch (status) {
                    case "SEM ESTOQUE":
                        // Vermelho Pastel (Suave)
                        c.setBackground(new Color(255, 204, 204));
                        break;
                    case "BAIXO ESTOQUE":
                        // Amarelo Pastel (Suave)
                        c.setBackground(new Color(255, 255, 204));
                        break;
                    case "OK":
                        // Verde Pastel (Suave)
                        c.setBackground(new Color(204, 255, 204));
                        break;
                    case "ALTO ESTOQUE":
                        // Azul Pastel (Suave)
                        c.setBackground(new Color(204, 229, 255));
                        break;
                    default:
                        c.setBackground(Color.WHITE);
                        break;
                }
            } else {
                // Quando selecionado, usa a cor padrão de seleção do sistema
                c.setBackground(table.getSelectionBackground());
                c.setForeground(table.getSelectionForeground());
            }

            // Alinhamento central
            setHorizontalAlignment(javax.swing.SwingConstants.CENTER);

            return c;
        }
    }

    public void carregarTabela() {
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setNumRows(0);

        ProdutoDAO dao = new ProdutoDAO();
        java.util.List<Object[]> produtos = dao.listarProdutosCompleto();

        for (Object[] p : produtos) {
            int qtd = (int) p[3];
            String alerta;

            // Lógica de texto refinada
            if (qtd == 0) {
                alerta = "SEM ESTOQUE";
            } else if (qtd < 10) {
                alerta = "BAIXO ESTOQUE";
            } else if (qtd < 30) {
                alerta = "OK";
            } else {
                alerta = "ALTO ESTOQUE";
            }

            modelo.addRow(new Object[]{p[0], p[1], p[2], p[3], alerta});
        }

        jLabel3.setText("TOTAL DE PRODUTOS: " + produtos.size());

    }

