    /**
     * Busca os produtos inativos no DAO e preenche o DefaultTableModel da
     * jTable1.
     */
    public void carregarTabelaInativos() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        modelo.setNumRows(0); // Limpa a tabela antes de carregar

        dao.ProdutoDAO dao = new dao.ProdutoDAO();

        // Percorre a lista retornada pelo banco e adiciona linha por linha na tabela
        for (Object[] p : dao.listarProdutosInativos()) {
            modelo.addRow(p);
        }
    }

