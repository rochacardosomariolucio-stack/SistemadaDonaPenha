    /**
     * Botão 1: RESTAURAR SELECIONADO Pega o ID da linha selecionada e altera o
     * status no banco para 'Ativo'.
     */
    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int linha = jTable1.getSelectedRow(); // Verifica qual linha o usuário clicou

        if (linha != -1) { // -1 significa que nada foi selecionado
            int id = (int) jTable1.getValueAt(linha, 0); // Pega o ID (coluna 0)
            String nome = (String) jTable1.getValueAt(linha, 1); // Obtém o Nome (coluna 1)

            // Tenta reativar no banco de dados
            dao.ProdutoDAO dao = new dao.ProdutoDAO();
            if (dao.reativarProduto(id)) {
                javax.swing.JOptionPane.showMessageDialog(this, nome + " foi restaurado com sucesso!");
                carregarTabelaInativos(); // Recarrega a tabela para remover o item que agora está ativo
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao restaurar no banco de dados.");
            }
        } else {
            // Caso o usuário clique em restaurar sem selecionar nada na grade
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um produto na tabela primeiro!");
        }
    }//GEN-LAST:event_jButton1ActionPerformed
