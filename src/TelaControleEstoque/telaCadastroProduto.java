    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            // 1. Coleta os dados da tela
            String nome = txtNome.getText().trim();
            String precoStr = txtPreco.getText().replace(",", ".");
            double preco = Double.parseDouble(precoStr);
            int qtd = (int) txtQtd.getValue();
            String nomeFornecedor = (String) cbFornecedor.getSelectedItem();

            if (nome.isEmpty() || precoStr.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Preencha todos os campos!");
                return;
            }

            // 2. Instancia o DAO e busca o ID do fornecedor selecionado
            dao.ProdutoDAO dao = new dao.ProdutoDAO();
            int idF = dao.buscarIdPeloNome(nomeFornecedor);

            // 3. Salva o novo produto no banco
            if (dao.cadastrarNovoProduto(nome, preco, qtd, idF)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Produto '" + nome + "' cadastrado com sucesso!");
                dispose(); // Fecha a tela de cadastro após o sucesso
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao salvar no banco de dados.");
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro no formato do preço. Use apenas números e ponto.");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ocorreu um erro inesperado: " + e.getMessage());
        }

    }//GEN-LAST:event_jButton2ActionPerformed

