    private void carregarFornecedores() {
        cbFornecedor.removeAllItems(); // Limpa a lista padrão do NetBeans

        // Use seu FornecedorDAO para buscar os nomes reais
        dao.FornecedorDAO fDao = new dao.FornecedorDAO();
        java.util.List<String> nomes = fDao.buscarNomesFornecedores();

        for (String nome : nomes) {
            cbFornecedor.addItem(nome);
        }
    }

