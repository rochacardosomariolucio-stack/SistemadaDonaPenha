    /**
     * BOTÃO: CONTATAR (Integração WhatsApp Web)
     */
    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        int linha = jTable1.getSelectedRow();

        if (linha != -1) {
            // Pega o telefone da coluna index 2 (WHATSAPP)
            String telefone = jTable1.getValueAt(linha, 2).toString();

            // Limpa o número (remove espaços, parênteses e traços)
            String numeroLimpo = telefone.replaceAll("[^0-9]", "");

            try {
                // Abre o WhatsApp Web com o número do fornecedor
                java.awt.Desktop.getDesktop().browse(new java.net.URI("https://wa.me/55" + numeroLimpo));
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao abrir o WhatsApp.");
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um fornecedor na tabela para contatar!");
        }
    }//GEN-LAST:event_jButton4ActionPerformed
/**
     * BOTÃO: GERENCIAR FORNECEDOR
     * Envia o ID e Nome para a tela de edição.
     */
    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
// 1. Verifica qual linha o usuário clicou na tabela de fornecedores
        int linhaSelecionada = jTable1.getSelectedRow();

        if (linhaSelecionada != -1) {
            // 2. Puxa o ID (coluna 0) e o Nome (coluna 1) da tabela
            // Verifique se a ordem das suas colunas na jTable1 é essa mesma
            int id = (int) jTable1.getValueAt(linhaSelecionada, 0);
            String nome = (String) jTable1.getValueAt(linhaSelecionada, 1);

            // 3. Abre a tela PASSANDO o id e o nome reais para o gerenciamento
            gerenciarFornecedor tgerenciar = new gerenciarFornecedor(id, nome);
            tgerenciar.setVisible(true);

            // 4. Opcional: Atualiza a lista quando a edição fechar
            tgerenciar.addWindowListener(new java.awt.event.WindowAdapter() {
                @Override
                public void windowClosed(java.awt.event.WindowEvent e) {
                    carregarTabelaFornecedores();
                }
            });
        } else {
            // Aviso se nada foi selecionado
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um fornecedor na tabela para gerenciar!");
        }
    }//GEN-LAST:event_jButton7ActionPerformed

    
