    // CARREGAR OS FORNECEDORES
    public void carregarTabelaFornecedores() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        modelo.setNumRows(0); // Limpa a tabela para evitar duplicidade

        dao.FornecedorDAO dao = new dao.FornecedorDAO();
        // Percorre a lista vinda do banco e adiciona na grade
        for (Object[] f : dao.listarFornecedoresCompleto()) {
            modelo.addRow(f);
        }
        // Atualiza o contador visual de fornecedores
        jLabel3.setText("TOTAL DE FORNECEDORES: " + modelo.getRowCount());
    }

