    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        int resp = JOptionPane.showConfirmDialog(this, "Inativar fornecedor " + nomeF + "?", "Atenção", JOptionPane.YES_NO_OPTION);
        if (resp == JOptionPane.YES_OPTION) {
            if (new dao.FornecedorDAO().inativarFornecedor(idF)) {
                JOptionPane.showMessageDialog(this, "Fornecedor enviado para a lixeira!");
                dispose();
            }
        }
    }//GEN-LAST:event_jButton4ActionPerformed

