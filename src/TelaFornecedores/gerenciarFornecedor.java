    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String novo = JOptionPane.showInputDialog(this, "Novo telefone (apenas números):");
        if (novo != null && !novo.trim().isEmpty()) {
            if (new dao.FornecedorDAO().atualizarTelefoneF(idF, novo)) {
                JOptionPane.showMessageDialog(this, "Contato atualizado!");
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String novo = JOptionPane.showInputDialog(this, "Nova cidade do fornecedor:");
        if (novo != null && !novo.trim().isEmpty()) {
            if (new dao.FornecedorDAO().atualizarCidadeF(idF, novo)) {
                JOptionPane.showMessageDialog(this, "Cidade atualizada!");
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String novo = JOptionPane.showInputDialog(this, "Novo nome para o fornecedor:", nomeF);
        if (novo != null && !novo.trim().isEmpty()) {
            if (new dao.FornecedorDAO().atualizarNomeF(idF, novo)) {
                JOptionPane.showMessageDialog(this, "Nome atualizado!");
                this.nomeF = novo;
                jLabel1.setText("GERENCIAR: " + novo.toUpperCase());
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

