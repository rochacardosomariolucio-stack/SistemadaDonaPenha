    public void carregarTabela() {
        GerenteDAO dao = new GerenteDAO();
        List<String> usuarios = dao.listarNomesUsuarios();

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setNumRows(0);
        modelo.setColumnIdentifiers(new String[]{"NOME DE USUÁRIO"});

        for (String nome : usuarios) {
            modelo.addRow(new Object[]{nome});
        }

        // 🚨 NOVO: Trava visual no botão de cadastro
        // Se já tiver 2 usuários, o botão "Novo Cadastro" fica cinza (desativado)
        if (dao.contarUsuarios() >= 2) {
            jButton2.setEnabled(false);
            jButton2.setToolTipText("Limite de 2 usuários atingido.");
        } else {
            jButton2.setEnabled(true);
        }
    }

