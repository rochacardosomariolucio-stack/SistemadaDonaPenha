    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int linha = jTable1.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, selecione um usuário na tabela.");
            return;
        }

        String nomeAlvo = jTable1.getValueAt(linha, 0).toString();

        // Não deixa remover o 'admin'
        if (nomeAlvo.equalsIgnoreCase("admin")) {
            JOptionPane.showMessageDialog(this, "A conta 'admin' é vital para o sistema e não pode ser removida.", "Acesso Negado", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String usuarioLogado = SessaoUsuario.getUsuarioLogado();
        String avisoAdicional = nomeAlvo.equals(usuarioLogado) ? "\n(AVISO: Você está logado nesta conta. O sistema fechará completamente após a remoção.)" : "";

        int confirm = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja remover o usuário '" + nomeAlvo + "'?" + avisoAdicional, "Confirmar Exclusão", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            GerenteDAO dao = new GerenteDAO();
            if (dao.deletarGerente(nomeAlvo)) {
                JOptionPane.showMessageDialog(this, "Usuário removido com sucesso!");

                // 🚨 LOGICA DE DESCONEXÃO TOTAL
                if (nomeAlvo.equals(usuarioLogado)) {
                    // Percorre e fecha TODAS as janelas (TelaPrincipal, Relatórios, etc)
                    for (java.awt.Window window : java.awt.Window.getWindows()) {
                        window.dispose();
                    }
                    // Abre apenas a tela de login
                    new TelaLogin.telalogin().setVisible(true);
                } else {
                    // Se removeu o outro gerente, apenas atualiza a lista na tela atual
                    carregarTabela();
                }
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

